// Masks for C0 control codes {{{

// There is no unsigned byte comparison before AVX512, so use:
// min(x, 0x1f) == x <=> x <= 0x1f
func c0_mask16(v, below_space, del archsimd.Uint8x16) archsimd.Mask8x16 {
	return v.Min(below_space).Equal(v).Or(v.Equal(del))
}

func c0_mask32(v, below_space, del archsimd.Uint8x32) archsimd.Mask8x32 {
	return v.Min(below_space).Equal(v).Or(v.Equal(del))
}

func c0_mask64(v, space, del archsimd.Uint8x64) archsimd.Mask8x64 {
	return v.Less(space).Or(v.Equal(del))
}

