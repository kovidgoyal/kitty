// Implementations using the amd64 specific simd/archsimd package. These are
// faster than the vector size agnostic code in simd.go because:
//
//   - The portable API has no way to turn a mask into a bitmask, and while
//     Mask8s.ToArch() can be used to get at ToBits() (VPMOVMSKB/KMOVQ) it
//     boxes the mask into an interface, which costs a store and a reload of
//     the vector on every loop iteration.
//   - Partial loads of 16 and 32 bytes are a chain of branches and scalar
//     inserts implemented as a function call, while here data of 16 bytes
//     or more is handled with overlapping 16 or 32 byte loads and shorter
//     data with overlapping scalar loads.
//   - After the first vector, loads are aligned to the vector size, so they
//     never cross cache lines, which is particularly important for AVX512,
//     where every unaligned load crosses a cache line.
//   - AVX512 has unsigned byte comparison, used for C0 detection.
//   - The "not" variants invert the bitmask in a general purpose register
//     rather than the vector.

// SIMD implementations available at runtime, fastest first
func simd_impls() []*impl_set {
	var ans *impl_set
	switch simd_vector_size() {
	case 0:
		// emulated, slower than scalar code
		return nil
	case 16:
		ans = &impl_set{
			"avx",
			index_byte_16, func(t string, b byte) int { return index_byte_16(bytes_of_string(t), b) },
			index_byte2_16, func(t string, a, b byte) int { return index_byte2_16(bytes_of_string(t), a, b) },
			index_c0_16, func(t string) int { return index_c0_16(bytes_of_string(t)) },
			not_index_byte_16, func(t string, b byte) int { return not_index_byte_16(bytes_of_string(t), b) },
			not_index_byte2_16, func(t string, a, b byte) int { return not_index_byte2_16(bytes_of_string(t), a, b) },
		}
	case 32:
		ans = &impl_set{
			"avx2",
			index_byte_32, func(t string, b byte) int { return index_byte_32(bytes_of_string(t), b) },
			index_byte2_32, func(t string, a, b byte) int { return index_byte2_32(bytes_of_string(t), a, b) },
			index_c0_32, func(t string) int { return index_c0_32(bytes_of_string(t)) },
			not_index_byte_32, func(t string, b byte) int { return not_index_byte_32(bytes_of_string(t), b) },
			not_index_byte2_32, func(t string, a, b byte) int { return not_index_byte2_32(bytes_of_string(t), a, b) },
		}
	default:
		ans = &impl_set{
			"avx512",
			index_byte_64, func(t string, b byte) int { return index_byte_64(bytes_of_string(t), b) },
			index_byte2_64, func(t string, a, b byte) int { return index_byte2_64(bytes_of_string(t), a, b) },
			index_c0_64, func(t string) int { return index_c0_64(bytes_of_string(t)) },
			not_index_byte_64, func(t string, b byte) int { return not_index_byte_64(bytes_of_string(t), b) },
			not_index_byte2_64, func(t string, a, b byte) int { return not_index_byte2_64(bytes_of_string(t), a, b) },
		}
	}
	return []*impl_set{ans, portable_impl()}
}

// The implementations, in simd_amd64_generated.go, generated by
// gen/simdstring.py, all work the same way:
//
//   - Data shorter than 16 bytes is handled with load_short16().
//   - Data shorter than two vectors of 16 (or for AVX512, 32) bytes is
//     handled with two overlapping loads, from the start and end of data.
//   - Otherwise, the first vector is loaded from the start of data, then
//     vectors are loaded from aligned addresses, several at a time, with a
//     single test and branch for all of them, then the matching vector is
//     located with a loop over single vectors and finally, the last vector
//     is loaded from the end of data.
//
// Overlapping loads are harmless, as the overlapping bytes are known to not
// match. Using unrolled loops is up to twice as fast for long data.

// Load a vector from p + off. Used instead of LoadUint8x*(data[off:]) as
// the compiler cannot prove such slicing in bounds in the unrolled loops
// and so adds several bounds checks and pointer masking per load.
func load16(p unsafe.Pointer, off int) archsimd.Uint8x16 {
	return archsimd.LoadUint8x16Array((*[16]byte)(unsafe.Add(p, off)))
}

func load32(p unsafe.Pointer, off int) archsimd.Uint8x32 {
	return archsimd.LoadUint8x32Array((*[32]byte)(unsafe.Add(p, off)))
}

func load64(p unsafe.Pointer, off int) archsimd.Uint8x64 {
	return archsimd.LoadUint8x64Array((*[64]byte)(unsafe.Add(p, off)))
}

// Return the index of the first set bit in the bitmasks lo and hi of two
// overlapping vectors loaded from data[:h] and data[l-h:], where h <= l < 2h
func pair_index(lo, hi uint64, h, l int) int {
	if m := lo | hi<<uint(l-h); m != 0 {
		return bits.TrailingZeros64(m)
	}
	return -1
}

// Return off + index of the lowest set bit in m or -1 if m is zero
func found_at16(off int, m uint16) int {
	if m == 0 {
		return -1
	}
	return off + bits.TrailingZeros16(m)
}

func found_at32(off int, m uint32) int {
	if m == 0 {
		return -1
	}
	return off + bits.TrailingZeros32(m)
}

func found_at64(off int, m uint64) int {
	if m == 0 {
		return -1
	}
	return off + bits.TrailingZeros64(m)
}

// Data shorter than 16 bytes {{{
// archsimd.LoadUint8x16Part() is a chain of branches and element inserts that
// is not inlined, and so requires spilling vectors around the call. Instead,
// use two overlapping scalar loads and convert the resulting bitmask into an
// index. Lanes not filled from data are discarded by short_index16().
// archsimd.LoadUint8x64Part() is not used either as, as of Go 1.27, it is
// compiled to a full 64 byte load followed by masking, instead of a masked
// load, and so can fault when the data is just before an unmapped page.

// Load 1 to 15 bytes into a vector without reading outside data. Returns
// the vector and k, the largest power of two <= len(data). The first k lanes
// are data[:k] and the next k lanes are data[len(data)-k:], overlapping.
func load_short16(data []byte) (archsimd.Uint8x16, int) {
	var lo, hi uint64
	l, k := len(data), 8
	switch {
	case l >= 8:
		lo, hi = binary.LittleEndian.Uint64(data), binary.LittleEndian.Uint64(data[l-8:])
	case l >= 4:
		lo, k = uint64(binary.LittleEndian.Uint32(data))|uint64(binary.LittleEndian.Uint32(data[l-4:]))<<32, 4
	case l >= 2:
		lo, k = uint64(binary.LittleEndian.Uint16(data))|uint64(binary.LittleEndian.Uint16(data[l-2:]))<<16, 2
	default:
		lo, k = uint64(data[0])*0x101, 1
	}
	return archsimd.Uint64x2{}.SetElem(0, lo).SetElem(1, hi).AsUint8x16(), k
}

// Convert the bitmask for a vector returned by load_short16() for l bytes
// to the index of the first matching byte or -1. The bits for the second k
// lanes are moved to the positions in data they were loaded from.
func short_index16(m uint16, k, l int) int {
	low := uint32(1)<<uint(k) - 1
	if m := uint32(m)&low | (uint32(m)>>uint(k)&low)<<uint(l-k); m != 0 {
		return bits.TrailingZeros32(m)
	}
	return -1
}

