type MouseEventType uint
type MouseButtonFlag uint

const (
	MOUSE_PRESS MouseEventType = iota
	MOUSE_RELEASE
	MOUSE_MOVE
	MOUSE_CLICK
	MOUSE_LEAVE
	// A scroll event reported with detailed mouse events, see
	// Loop.DetailedMouseEvents(). The details are in MouseEvent.Wheel.
	MOUSE_WHEEL
	// The mouse entered the window, reported only with detailed mouse events
	MOUSE_ENTER
)

func (e MouseEventType) String() string {
	switch e {
	case MOUSE_PRESS:
		return "press"
	case MOUSE_RELEASE:
		return "release"
	case MOUSE_MOVE:
		return "move"
	case MOUSE_CLICK:
		return "click"
	case MOUSE_LEAVE:
		return "leave"
	case MOUSE_WHEEL:
		return "wheel"
	case MOUSE_ENTER:
		return "enter"
	}
	return strconv.Itoa(int(e))
}

