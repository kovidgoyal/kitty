type MouseEventType uint
type MouseButtonFlag uint

const (
	MOUSE_PRESS MouseEventType = iota
	MOUSE_RELEASE
	MOUSE_MOVE
	MOUSE_CLICK
	MOUSE_LEAVE
	// A scroll event reported with detailed wheel events, see
	// Loop.DetailedWheelEvents(). The details are in MouseEvent.Wheel.
	MOUSE_WHEEL
)

func (e MouseEventType) String() string {
	switch e {
	case MOUSE_PRESS:
		return "press"
	case MOUSE_RELEASE:
		return "release"
	case MOUSE_MOVE:
		return "move"
	case MOUSE_CLICK:
		return "click"
	case MOUSE_LEAVE:
		return "leave"
	case MOUSE_WHEEL:
		return "wheel"
	}
	return strconv.Itoa(int(e))
}

